// Extracts the local Hardhat test wallets from the node startup log,
// cryptographically verifies each private key derives to its stated address,
// confirms each is funded on the running node, then writes TEST_WALLETS.md.
const fs = require('fs');
const path = require('path');
const os = require('os');
const { ethers } = require(path.join(__dirname, 'node_modules', 'ethers'));

const LOG = path.join(os.tmpdir(), 'hh-node2.log');
const OUT = path.join(__dirname, 'TEST_WALLETS.md');

const NETWORK = {
  name: 'Hardhat Local',
  rpc: 'http://127.0.0.1:8545',
  chainId: '31337',
  currency: 'ETH',
};

async function main() {
  const log = fs.readFileSync(LOG, 'utf8');
  const re = /Account #(\d+): (0x[0-9a-fA-F]{40})[^\n]*\nPrivate Key: (0x[0-9a-fA-F]{64})/g;
  const accounts = [];
  let m;
  while ((m = re.exec(log)) !== null) {
    accounts.push({ n: +m[1], addr: m[2], key: m[3] });
  }
  if (accounts.length === 0) throw new Error('No accounts parsed from node log: ' + LOG);
  console.log('Parsed', accounts.length, 'accounts from node log');

  // Verify: key -> address matches, and address is funded on the live node.
  const provider = new ethers.JsonRpcProvider(NETWORK.rpc);
  const rows = [];
  let bad = 0;
  for (const a of accounts) {
    const derived = new ethers.Wallet(a.key).address;
    const addrOk = derived.toLowerCase() === a.addr.toLowerCase();
    let bal = 0n;
    let balOk = false;
    try {
      bal = await provider.getBalance(a.addr);
      balOk = bal > 0n;
    } catch (e) {
      balOk = false;
    }
    if (!addrOk || !balOk) {
      bad++;
      console.log('  !! account', a.n, 'addrOk=' + addrOk, 'funded=' + balOk);
    }
    rows.push({ ...a, bal: ethers.formatEther(bal), addrOk, balOk });
  }
  console.log('Verified', rows.length - bad, '/', rows.length,
    '(key derives to address + funded on node)');
  if (bad > 0) {
    console.log('WARNING:', bad, 'account(s) failed verification — aborting write.');
    process.exit(1);
  }

  const short = (a) => a.slice(0, 6) + '\u2026' + a.slice(-4);
  const lines = [];
  lines.push('# DecentraPay \u2014 Local Test Wallets');
  lines.push('');
  lines.push('> **These are publicly-known, throwaway development wallets.** They are');
  lines.push('> generated deterministically by Hardhat and printed in every Hardhat node\u2019s');
  lines.push('> startup output. Their private keys are public information.');
  lines.push('>');
  lines.push('> **Never send real ETH or use these on mainnet or any public network \u2014');
  lines.push('> anyone who sees this file can steal whatever is in these wallets.** They are');
  lines.push('> only for the local Hardhat node in this project. All funds below are fake');
  lines.push('> test ETH with no real value.');
  lines.push('');
  lines.push('## Network');
  lines.push('');
  lines.push('| Setting | Value |');
  lines.push('|---------|-------|');
  lines.push('| Network name | `' + NETWORK.name + '` |');
  lines.push('| RPC URL | `' + NETWORK.rpc + '` |');
  lines.push('| Chain ID | `' + NETWORK.chainId + '` |');
  lines.push('| Currency symbol | `' + NETWORK.currency + '` |');
  lines.push('');
  lines.push('## How to import into MetaMask');
  lines.push('');
  lines.push('1. MetaMask menu (top-right) \u2192 **Import account**');
  lines.push('2. Paste one of the **Private Keys** below');
  lines.push('3. Add the network using the table above (or use the built-in');
  lines.push('   "Hardhat Local" / Localhost 8545 entry)');
  lines.push('');
  lines.push('## Accounts');
  lines.push('');
  lines.push('| # | Address | Private Key | Test Balance |');
  lines.push('|---|---------|-------------|--------------|');
  for (const r of rows) {
    lines.push('| ' + r.n + ' | `' + r.addr + '` | `' + r.key + '` | ' + r.bal + ' ETH |');
  }
  lines.push('');
  lines.push('## Recommended for this project');
  lines.push('');
  lines.push('| Role | Account # | Address |');
  lines.push('|------|-----------|---------|');
  lines.push('| Sender (deploy / pay from) | 0 | `' + rows[0].addr + '` |');
  if (rows[1]) lines.push('| Receiver (pay to) | 1 | `' + rows[1].addr + '` |');
  lines.push('');
  lines.push('Account #0 deployed the DecentraPay contract at');
  lines.push('`0x5FbDB2315678afecb367f032d93F642f64180aa3` (see');
  lines.push('`frontend/src/utils/constants.js`).');
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('_Generated by `extract-wallets.js`. Regenerate after restarting the');
  lines.push('Hardhat node if you use a custom mnemonic, since the default set is');
  lines.push('deterministic but a custom one would differ._');

  fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
  console.log('Wrote', OUT, '(' + rows.length + ' accounts)');
}

main().catch((e) => {
  console.error('ERROR:', e.message);
  process.exit(1);
});
